from pathlib import Path
import os
import unittest
from unittest.mock import patch

from lab.config import load_config
from lab.knowledge import SEARCH_API, knowledge_payloads, resource_names, search_url


class KnowledgeTests(unittest.TestCase):
    def setUp(self):
        self.config = load_config(Path(__file__).resolve().parents[1] / ".env.example")
        self.names = resource_names(self.config, {"workspace_id": "12345678-1234-1234-1234-123456789012"})
        self.payloads = knowledge_payloads(self.config, self.names, "gpt-5.5")

    def test_stable_ids_are_retrievable_and_not_autogenerated_chunks(self):
        fields = self.payloads["index"]["fields"]
        identifier = next(field for field in fields if field["name"] == "id")
        self.assertTrue(identifier["key"])
        self.assertTrue(identifier["retrievable"])
        self.assertEqual(self.payloads["source"]["kind"], "searchIndex")

    def test_lexical_analyzers_match_the_selected_policy_language(self):
        for language in ("ko", "en"):
            with self.subTest(language=language), patch.dict(os.environ, {"LAB_LANGUAGE": language}):
                payload = knowledge_payloads(self.config, self.names, "gpt-5.5")
                fields = {field["name"]: field for field in payload["index"]["fields"]}
                self.assertEqual(fields["title"]["analyzer"], f"{language}.microsoft")
                self.assertEqual(fields["content"]["analyzer"], f"{language}.microsoft")
                self.assertEqual(fields["content_vector"]["dimensions"], 1536)

    def test_source_data_fields_are_on_the_source_not_the_base(self):
        self.assertIn("sourceDataFields", self.payloads["source"]["searchIndexParameters"])
        self.assertNotIn("sourceDataFields", self.payloads["base"])

    def test_full_iq_low_planning_and_extractive_output_are_explicit(self):
        base = self.payloads["base"]
        self.assertEqual(base["retrievalReasoningEffort"], {"kind": "low"})
        self.assertEqual(base["outputMode"], "extractiveData")
        model = base["models"][0]["azureOpenAIParameters"]
        self.assertEqual(model["deploymentId"], "workshop-optimizer")
        self.assertEqual(model["modelName"], "gpt-5.5")

    def test_runtime_connection_uses_project_identity_not_a_key(self):
        properties = self.payloads["connection"]["properties"]
        self.assertEqual(properties["authType"], "ProjectManagedIdentity")
        self.assertEqual(properties["category"], "RemoteTool")
        self.assertNotIn("credentials", properties)
        self.assertFalse(properties["isSharedToAll"])
        self.assertIn(f"api-version={SEARCH_API}", properties["target"])

    def test_resources_are_namespaced_by_workspace_not_only_shared_prefix(self):
        self.assertTrue(all("12345678" in name for name in self.names.values()))
        url = search_url(self.config, "knowledgebases", self.names["base"], "/mcp")
        self.assertEqual(url, self.payloads["connection"]["properties"]["target"])

    def test_real_vector_schema_and_query_vectorizer_are_bound(self):
        index = self.payloads["index"]
        vector = next(field for field in index["fields"] if field["name"] == "content_vector")
        self.assertEqual(vector["dimensions"], 1536)
        self.assertEqual(vector["vectorSearchProfile"], "contoso-vector")
        vectorizer = index["vectorSearch"]["vectorizers"][0]["azureOpenAIParameters"]
        self.assertEqual(vectorizer["deploymentId"], self.config.embedding)
        self.assertEqual(vectorizer["modelName"], "text-embedding-3-small")
        self.assertIn({"name": "content_vector"}, self.payloads["source"]["searchIndexParameters"]["searchFields"])


if __name__ == "__main__":
    unittest.main()
